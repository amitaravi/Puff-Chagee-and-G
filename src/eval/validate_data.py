"""
Contract validator. Person A runs this before handing data over; CI runs it on push.

    python -m src.eval.validate_data
    python -m src.eval.validate_data --strict   # also fail the 70/20/10 mix check

Exits non-zero on any failure, so it can be a CI step.
"""

from __future__ import annotations

import json
import os
import sys

from ..core.config import DATA_DIR, ROOT
from ..core.state import EvidencePack
from ..policy.apply_policy import apply_policy, policy_formula_namespace

LEAK_KEYS = {
    "correct_ruling", "correct_refund_amount", "correct_policy_id",
    "expected_confidence_band", "should_escalate", "ground_truth",
    "confidence_target", "_ground_truth",
}

TARGET_MIX = {"high": 0.70, "medium": 0.20, "low": 0.10}
MIX_TOLERANCE = 0.05


def main(argv=None) -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=DATA_DIR)
    ap.add_argument("--strict", action="store_true", help="fail on confidence-mix drift")
    args = ap.parse_args(argv)

    d = args.dir
    cases_dir = os.path.join(d, "cases")
    if not os.path.isdir(cases_dir):
        print(f"FAIL  no cases/ directory under {d}. Run scripts/generate_dataset.py first.")
        return 1

    failures: list[str] = []
    warnings: list[str] = []

    # ---------------------------------------------------------------- load
    policies = json.load(open(os.path.join(d, "policies.json"), encoding="utf-8"))
    pol_by_id = {p["policy_id"]: p for p in policies}
    gt = json.load(open(os.path.join(d, "ground_truth.json"), encoding="utf-8"))
    index = json.load(open(os.path.join(d, "index.json"), encoding="utf-8"))
    base_ids = set(index["splits"].get("dev", [])) | set(index["splits"].get("test", []))

    packs: dict[str, EvidencePack] = {}
    raws: dict[str, dict] = {}
    for fname in sorted(os.listdir(cases_dir)):
        if not fname.endswith(".json"):
            continue
        raw = json.load(open(os.path.join(cases_dir, fname), encoding="utf-8"))
        did = raw["dispute"]["dispute_id"]
        raws[did] = raw
        try:
            packs[did] = EvidencePack(**raw)
        except Exception as exc:  # noqa: BLE001
            failures.append(f"{fname}: does not parse as EvidencePack — {exc}")
            continue

        # ---- leakage. A leaked label makes the whole eval worthless, silently.
        blob = json.dumps(raw)
        for key in LEAK_KEYS:
            if f'"{key}"' in blob:
                failures.append(f"{did}: LEAKED ground-truth key '{key}' in the case file")

        pack = packs[did]
        cat = pack.dispute.category

        # ---- required evidence per category
        if cat == "route_deviation" and pack.route is None:
            failures.append(f"{did}: route_deviation with no route")
        if cat == "no_show" and pack.no_show is None:
            failures.append(f"{did}: no_show with no no_show facts")
        if cat == "damage_cleaning" and (pack.fraud is None or pack.fraud.photo_authenticity_score is None):
            warnings.append(f"{did}: damage claim with no photo authenticity score")

        # ---- internal consistency
        if pack.route:
            r = pack.route
            exp_km = round(r.actual_distance_km - r.optimal_distance_km, 2)
            if abs(exp_km - r.deviation_km) > 0.02:
                failures.append(f"{did}: route.deviation_km {r.deviation_km} != actual-optimal {exp_km}")
            exp_pct = r.deviation_km / r.optimal_distance_km if r.optimal_distance_km else 0.0
            if abs(exp_pct - r.deviation_pct) > 0.005:
                warnings.append(
                    f"{did}: route.deviation_pct {r.deviation_pct} vs deviation/optimal {exp_pct:.4f}")
            if r.deviation_pct > 1.5:
                failures.append(
                    f"{did}: route.deviation_pct {r.deviation_pct} looks like a PERCENT, "
                    f"not a fraction (0.176 means 17.6%)")

        # A no-show charge is a flat fee, not a sum of fare components — skip those.
        if pack.trip.status == "completed":
            f = pack.fare
            total = (f.base_fare + f.distance_fare + f.time_fare + f.booking_fee
                     + f.surge_amount + f.tolls - f.promo_discount)
            if abs(total - f.total_charged) > 0.05:
                failures.append(
                    f"{did}: fare.total_charged {f.total_charged} != components {round(total, 2)}")

        # ---- policies cited in ground truth must exist
        t = gt.get(did, {})
        pid = t.get("correct_policy_id")
        if pid and pid not in pol_by_id:
            has = any(p.policy_id == pid for p in pack.policies)
            if not has:
                failures.append(f"{did}: ground truth cites unknown policy {pid}")

        # ---- labels must match apply_policy (they were generated by it; drift is a bug)
        if did in gt:
            truth = apply_policy(pack)
            for key in ("correct_ruling", "should_escalate"):
                truth_attr = {"correct_ruling": "ruling", "should_escalate": "should_escalate"}[key]
                truth_val = getattr(truth, truth_attr)
                if gt[did].get(key) != truth_val:
                    failures.append(
                        f"{did}: stored label {key}={gt[did].get(key)!r} but "
                        f"apply_policy() now says {truth_val!r} — regenerate")

    # ---- policy formulas must be machine-checkable
    for pid, pol in pol_by_id.items():
        formula = pol.get("remedy_formula")
        if not formula:
            continue
        try:
            ns = {}
            for pack in packs.values():
                ns.update(policy_formula_namespace(pack))
                break
            compile(formula, "<formula>", "eval")
        except SyntaxError as exc:
            failures.append(f"{pid}: remedy_formula is not valid Python — {exc}")

    # ---- confidence mix
    bands: dict[str, int] = {}
    for did in base_ids:
        b = gt.get(did, {}).get("expected_confidence_band", "?")
        bands[b] = bands.get(b, 0) + 1
    n = len(base_ids)

    prec_path = os.path.join(d, "precedents.json")
    n_prec = len(json.load(open(prec_path, encoding="utf-8"))) if os.path.exists(prec_path) else 0
    print(f"\nValidated {len(packs)} cases in {os.path.relpath(d, ROOT)}/")
    print(f"  policies {len(policies)} · precedents {n_prec}")
    print(f"\n  base cases {n} · probe cases {len(packs) - n}")
    print("\n  confidence mix (target 70/20/10):")
    for band in ("high", "medium", "low"):
        c = bands.get(band, 0)
        share = c / n if n else 0
        flag = ""
        if abs(share - TARGET_MIX[band]) > MIX_TOLERANCE:
            flag = "  <-- off target"
            if args.strict:
                failures.append(f"confidence mix {band}={share:.1%} off target "
                                f"{TARGET_MIX[band]:.0%} by more than {MIX_TOLERANCE:.0%}")
        print(f"    {band:<7} {c:>4}  {share:>6.1%}{flag}")

    for w in warnings[:15]:
        print(f"\n  WARN  {w}")
    if len(warnings) > 15:
        print(f"\n  ... and {len(warnings) - 15} more warnings")

    if failures:
        print(f"\nFAILED with {len(failures)} error(s):")
        for x in failures[:30]:
            print(f"  - {x}")
        if len(failures) > 30:
            print(f"  ... and {len(failures) - 30} more")
        return 1

    print("\nOK — data/ satisfies the contract.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
